"""Provision the dependencies pixi does not package.

These are small, and they are the only pieces of the third-party stack that are compiled with
opendcc's own environment (Qt for the docking system, the SDK for sentry, OpenMesh for the
viewport tools). libigl is header-only, so "provisioning" it means unpacking its headers.
"""

from __future__ import annotations

import hashlib
import shutil
import tarfile
import urllib.request
import zipfile
from pathlib import Path

from . import pixi
from .cmake_build import toolchain_environment
from .plan import Plan
from .versions import SourceComponent, Versions

LIBIGL = "libigl"


class SourceError(RuntimeError):
    pass


def provision(plan: Plan, versions: Versions, verbose: bool = True) -> None:
    """Make every source-built dependency available under the plan's deps prefix."""
    for name in ("libigl", "qtads", "sentry", "openmesh"):
        component = plan.source(name, versions)
        marker = _marker(plan, name, component)
        if marker.is_file() and _is_complete(plan, name):
            if verbose:
                print(f"{name} {component.version} already provisioned", flush=True)
            continue
        if verbose:
            print(f"provisioning {name} {component.version}", flush=True)
        _provision_one(plan, name, component, verbose)
        marker.write_text(component.version + "\n")


def _is_complete(plan: Plan, name: str) -> bool:
    if name == LIBIGL:
        return (plan.deps_prefix / "libigl" / "include" / "igl" / "igl_inline.h").is_file()
    if name == "sentry":
        return any((plan.deps_prefix / "lib" / "cmake" / d).is_dir() for d in ("sentry",))
    if name == "qtads":
        stub = "qtadvanceddocking-qt6" if not plan.platform.startswith("win") else "qtadvanceddocking"
        return any(
            (plan.deps_prefix / "lib" / "cmake" / d).is_dir()
            for d in (stub, "qtadvanceddocking")
        )
    if name == "openmesh":
        return (plan.deps_prefix / "include" / "OpenMesh" / "Core" / "Mesh" / "PolyMeshT.hh").is_file()
    return True


def _marker(plan: Plan, name: str, component: SourceComponent) -> Path:
    # A source dependency is only valid for the environment it was compiled in.
    fingerprint = hashlib.sha256(
        "|".join(
            [
                component.version,
                component.url,
                str(plan.platform),
                plan.pins.get("python", ""),
                plan.pins.get("qt", ""),
                plan.pins.get("pyside", ""),
            ]
        ).encode()
    ).hexdigest()[:12]
    return plan.deps_prefix / f".{name}-{component.version}-{fingerprint}.stamp"


def _provision_one(
    plan: Plan, name: str, component: SourceComponent, verbose: bool
) -> None:
    if name == LIBIGL:
        archive = download(component, plan.root, verbose)
        target = plan.deps_prefix / "libigl"
        if target.exists():
            shutil.rmtree(target)
        extract(archive, target, strip=1)
        return

    source_dir = plan.build_dir / "src" / name
    archive = download(component, plan.root, verbose)
    if source_dir.exists():
        shutil.rmtree(source_dir)
    source_dir.parent.mkdir(parents=True, exist_ok=True)
    extract(archive, source_dir, strip=1)

    build_dir = plan.build_dir / "src" / f"{name}-build"
    if build_dir.exists():
        shutil.rmtree(build_dir)
    cmake = [
        "cmake",
        "-S",
        str(source_dir),
        "-B",
        str(build_dir),
        "-G",
        "Ninja",
        "-DCMAKE_BUILD_TYPE=Release",
        f"-DCMAKE_INSTALL_PREFIX={plan.deps_prefix}",
        f"-DCMAKE_PREFIX_PATH={plan.env_prefix}",
        f"-DPython3_EXECUTABLE={plan.python}",
    ]
    cmake += _component_options(name, component, plan)
    env = toolchain_environment()
    pixi.run(plan.manifest, cmake, env=env, verbose=verbose)
    pixi.run(
        plan.manifest,
        ["cmake", "--build", str(build_dir), "--target", "install"],
        env=env,
        verbose=verbose,
    )


def _component_options(name: str, component: SourceComponent, plan: Plan) -> list[str]:
    if name == "qtads":
        # ADS derives its version from git; a release tarball has none, so it is passed in.
        # Its src/CMakeLists.txt links Qt6::GuiPrivate without asking for the component, which
        # only works on a Qt that exports it unconditionally. Requesting it from a project hook
        # is enough: the private headers ship with conda-forge's qt6-main.
        hook = plan.build_dir / "src" / "qtads-project-include.cmake"
        hook.parent.mkdir(parents=True, exist_ok=True)
        hook.write_text(
            "# Generated by tools/build/opendcc-build.\n"
            "find_package(Qt6 QUIET COMPONENTS GuiPrivate)\n"
        )
        return [
            f"-DADS_VERSION={component.version}",
            "-DBUILD_EXAMPLES=OFF",
            "-DBUILD_STATIC=OFF",
            f"-DCMAKE_PROJECT_INCLUDE={hook}",
        ]
    if name == "sentry":
        # Crashpad is only needed by the in-app crash reporter, which is off by default; a
        # backend-less build still provides the sentry API opendcc compiles against.
        return [
            "-DSENTRY_BACKEND=none",
            "-DSENTRY_BUILD_TESTS=OFF",
            "-DSENTRY_BUILD_EXAMPLES=OFF",
            "-DCMAKE_POSITION_INDEPENDENT_CODE=ON",
        ]
    if name == "openmesh":
        # OpenMesh 9.0 declares cmake_minimum_required(VERSION 3.x) with x < 5, which CMake 4
        # rejects outright; the escape hatch keeps the policies at the level it was written for.
        return [
            "-DCMAKE_POLICY_VERSION_MINIMUM=3.5",
            "-DBUILD_APPS=OFF",
            "-DBUILD_UNIT_TESTS=OFF",
            "-DOPENMESH_BUILD_UNIT_TESTS=OFF",
            "-DOPENMESH_BUILD_PYTHON_UNIT_TESTS=OFF",
        ]
    return []


def download(component: SourceComponent, root: Path, verbose: bool = True) -> Path:
    """Fetch a source archive into the shared download cache.

    The cache file is named after the component and its version, not after the last URL
    segment: releases are frequently just a tag ("v2.6.0", "4.4.1"), which would collide
    between components in a shared cache.
    """
    cache = root / "build" / "downloads"
    cache.mkdir(parents=True, exist_ok=True)
    target = cache / f"{component.name}-{component.version}{_archive_suffix(component.url)}"
    if target.is_file() and target.stat().st_size > 0:
        return target
    if verbose:
        print(f"downloading {component.url}", flush=True)
    request = urllib.request.Request(component.url, headers={"User-Agent": "opendcc-build"})
    partial = target.with_suffix(target.suffix + ".part")
    with urllib.request.urlopen(request) as response, partial.open("wb") as out:
        shutil.copyfileobj(response, out)
    partial.replace(target)
    return target


def _archive_suffix(url: str) -> str:
    last = url.split("?")[0].rstrip("/").rsplit("/", 1)[-1]
    for suffix in (".tar.gz", ".tar.xz", ".tar.bz2", ".tgz", ".zip"):
        if last.endswith(suffix):
            return suffix
    return ""


def extract(archive: Path, target: Path, strip: int = 0) -> None:
    """Unpack `archive` into `target`, which only ever appears complete.

    Unpacking goes to a sibling staging directory that replaces `target` at the end, so an
    interrupted extraction never leaves a half-populated tree behind and re-running a step
    that already unpacked reuses the result instead of nesting a second copy inside it.
    """
    if target.is_dir() and any(target.iterdir()):
        return
    staging = target.with_name(target.name + ".unpacking")
    if staging.is_dir():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)
    if archive.suffix in (".zip",):
        with zipfile.ZipFile(archive) as handle:
            handle.extractall(staging)
    else:
        with tarfile.open(archive) as handle:
            if hasattr(tarfile, "data_filter"):
                handle.extractall(staging, filter="data")
            else:  # python < 3.12
                handle.extractall(staging)
    if strip:
        _strip_single_directory(staging, archive)
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.is_dir():
        target.rmdir()
    staging.replace(target)


def _strip_single_directory(target: Path, archive: Path) -> None:
    entries = [entry for entry in target.iterdir()]
    if len(entries) != 1 or not entries[0].is_dir():
        raise SourceError(f"{archive.name} does not contain a single top-level directory")
    top = entries[0]
    for entry in top.iterdir():
        shutil.move(str(entry), str(target / entry.name))
    top.rmdir()
