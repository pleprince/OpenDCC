"""Configure, build, install and test opendcc inside a plan's pixi environment."""

from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path

from . import pixi
from .plan import Plan, cmake_cache


class BuildError(RuntimeError):
    pass


def configure(plan: Plan, extra: list[str] | None = None, verbose: bool = True) -> None:
    plan.cmake_dir.mkdir(parents=True, exist_ok=True)
    argv = ["cmake", "-S", str(plan.root), "-B", str(plan.cmake_dir), "-G", "Ninja"]
    argv += [f"-D{key}={value}" for key, value in cmake_cache(plan).items()]
    argv += extra or []
    _run_in(plan, argv, verbose)


def build(
    plan: Plan,
    jobs: int | None = None,
    target: str | None = None,
    verbose: bool = True,
) -> None:
    _require_configured(plan)
    argv = ["cmake", "--build", str(plan.cmake_dir)]
    if target:
        argv += ["--target", target]
    if jobs:
        argv += ["--parallel", str(jobs)]
    _run_in(plan, argv, verbose)


def install(plan: Plan, verbose: bool = True) -> None:
    _require_configured(plan)
    _run_in(plan, ["cmake", "--install", str(plan.cmake_dir)], verbose)
    write_environment_script(plan, verbose)


def write_environment_script(plan: Plan, verbose: bool = True) -> None:
    """Write <install>/opendcc-env.sh/.ps1: the environment this install needs to run.

    The install links Qt, boost, OpenUSD and the source-built dependencies from the build tree,
    not from copies inside the install prefix, so launching it needs the environment's library
    paths. Sourcing the generated file is the supported way to do that; the redistributable
    packaging options (DCC_INSTALL_*) are what copy the libraries in instead.
    """
    if not plan.install_dir.is_dir():
        return
    unix = not plan.platform.startswith("win")
    # The install's own libraries come first: an installed binary has no rpath, so it finds
    # libopendcc_* and the Hydra delegates through this variable.
    prefix_bits = [
        plan.install_dir / "lib",
        plan.install_dir / "plugin" / "usd",
        plan.usd_prefix / "lib",
        plan.deps_prefix / "lib",
        plan.env_cmake_prefix / "lib",
    ]
    path_bits = [
        plan.install_dir / "bin",
        # A Windows OpenUSD installs its DLLs next to the import libraries, not in bin/.
        plan.usd_prefix / "lib",
        plan.usd_prefix / "bin",
        plan.deps_prefix / "bin",
        plan.env_cmake_prefix / "bin",
    ]
    python_bits = [plan.usd_prefix / "lib" / "python"]
    # USD plugin metadata: ar/sdf/... live in lib/usd/<lib>/resources, the Hydra delegates and
    # opendcc's own plugins in plugin/usd.
    plugin_bits = [
        plan.usd_prefix / "lib" / "usd",
        plan.usd_prefix / "plugin" / "usd",
        plan.install_dir / "plugin" / "usd",
    ]
    site_packages = plan.install_dir / "lib" / f"python{_python_minor(plan)}" / "site-packages"

    if unix:
        hook = pixi.shell_hook(plan.manifest, "bash")
        library_variable = "DYLD_LIBRARY_PATH" if plan.platform.startswith("osx") else "LD_LIBRARY_PATH"
        lines = [
            "# Generated by tools/build/opendcc-build; source this before running the install.",
            f"# OpenDCC built against OpenUSD {plan.release}: {plan.install_dir}",
            hook.rstrip(),
            f'export {library_variable}="{":".join(str(p) for p in prefix_bits)}:${library_variable}"',
            f'export PATH="{":".join(str(p) for p in path_bits)}:$PATH"',
            f'export PYTHONPATH="{":".join(str(p) for p in python_bits)}:{site_packages}:$PYTHONPATH"',
            f'export PXR_PLUGINPATH_NAME="{":".join(str(p) for p in plugin_bits)}:$PXR_PLUGINPATH_NAME"',
            "",
        ]
        target = plan.install_dir / "opendcc-env.sh"
    else:
        hook = pixi.shell_hook(plan.manifest, "powershell")
        lines = [
            "# Generated by tools/build/opendcc-build; dot-source this before running the install.",
            f"# OpenDCC built against OpenUSD {plan.release}: {plan.install_dir}",
            hook.rstrip(),
            '$env:Path = "' + ";".join(str(p) for p in path_bits) + ';$env:Path"',
            '$env:PYTHONPATH = "' + ";".join(str(p) for p in python_bits) + ";" + str(site_packages) + ';$env:PYTHONPATH"',
            '$env:PXR_PLUGINPATH_NAME = "' + ";".join(str(p) for p in plugin_bits) + ';$env:PXR_PLUGINPATH_NAME"',
            "",
        ]
        target = plan.install_dir / "opendcc-env.ps1"

    target.write_text("\n".join(lines))
    if verbose:
        print(f"environment script: {target}", flush=True)


def _python_minor(plan: Plan) -> str:
    version = plan.resolved.get("python") or "3"
    parts = version.split(".")
    return ".".join(parts[:2]) if len(parts) >= 2 else version


def test(plan: Plan, verbose: bool = True, extra: list[str] | None = None) -> None:
    _require_configured(plan)
    argv = [
        "ctest",
        "--test-dir",
        str(plan.cmake_dir),
        "--output-on-failure",
        *(extra or []),
    ]
    _run_in(plan, argv, verbose)


def _require_configured(plan: Plan) -> None:
    if not (plan.cmake_dir / "CMakeCache.txt").is_file():
        raise BuildError(
            f"{plan.cmake_dir} is not configured yet; run `pixi run configure` first"
        )


def _run_in(plan: Plan, argv: list[str], verbose: bool) -> None:
    pixi.run(
        plan.manifest,
        argv,
        cwd=plan.root,
        env=toolchain_environment(),
        verbose=verbose,
    )


def toolchain_environment() -> dict[str, str]:
    """Platform fixes applied to every command that runs a compiler.

    Windows has no compiler on PATH by default: Ninja needs cl.exe, so the Visual Studio
    developer environment is imported from VsDevCmd.bat when it is not already active. Everything
    else (macOS, Linux) uses the toolchain pixi installed or the system one.
    """
    env = dict(os.environ)
    if not plan_platform_is_windows():
        return env
    _ensure_utf8_sources(env)
    if shutil.which("cl"):
        return env

    vswhere = Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")) / (
        r"Microsoft Visual Studio\Installer\vswhere.exe"
    )
    if not vswhere.is_file():
        raise BuildError(
            "Visual Studio 2022 with the C++ workload is required on Windows and was not found "
            f"({vswhere}). Install 'Build Tools for Visual Studio 2022' with "
            "'Desktop development with C++'."
        )
    install_root = subprocess.run(
        [
            str(vswhere),
            "-latest",
            "-products",
            "*",
            "-requires",
            "Microsoft.VisualStudio.Component.VC.Tools.x86.x64",
            "-property",
            "installationPath",
        ],
        capture_output=True,
        text=True,
        check=False,
    ).stdout.strip()
    if not install_root:
        raise BuildError(
            "vswhere found no Visual Studio installation with the C++ tools; install "
            "'Desktop development with C++' for Visual Studio 2022"
        )
    dev_cmd = Path(install_root) / "Common7" / "Tools" / "VsDevCmd.bat"
    result = subprocess.run(
        ["cmd", "/c", f'call "{dev_cmd}" -arch=amd64 -host_arch=amd64 && set'],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise BuildError(f"failed to import the Visual Studio environment: {result.stdout}")
    for line in result.stdout.splitlines():
        if "=" in line:
            key, _, value = line.partition("=")
            if key and value:
                env[key] = value
    return env


def _ensure_utf8_sources(env: dict[str, str]) -> None:
    """Ask MSVC to compile as UTF-8.

    Third-party CMake builds (OpenUSD, the source dependencies) initialize their flag cache
    from the environment. OpenImageIO 3.1 vendors fmt, whose headers static_assert that the
    literal encoding is UTF-8, so every translation unit that includes its headers needs it.
    """
    for name in ("CFLAGS", "CXXFLAGS"):
        if "/utf-8" not in env.get(name, ""):
            env[name] = f"{env.get(name, '')} /utf-8".strip()


def plan_platform_is_windows() -> bool:
    return pixi.platform_key().startswith("win")
